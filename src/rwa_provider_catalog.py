def build_provider_catalog(
    *,
    category: str = "all",
    status: str = "all",
) -> dict[str, Any]:
    """Return provider catalog entries and ingestion jobs for expansion work."""
    category_filter = category.strip().lower()
    status_filter = status.strip().lower()
    if category_filter != "all" and category_filter not in PROVIDER_CATEGORIES:
        raise ValueError(f"Unsupported provider category: {category}")
    if status_filter not in SUPPORTED_PROVIDER_STATUSES:
        raise ValueError(f"Unsupported provider status: {status}")

    providers = [_provider_row(row) for row in PROVIDER_CATALOG]
    if category_filter != "all":
        providers = [row for row in providers if row["category"] == category_filter]
    if status_filter != "all":
        providers = [row for row in providers if row["ingestion_status"] == status_filter]

    jobs = [_ingestion_job(row) for row in providers]
    by_category = Counter(str(row["category"]) for row in providers)
    by_status = Counter(str(row["ingestion_status"]) for row in providers)
    by_region = Counter(str(row["region"]) for row in providers)
    by_access_model = Counter(str(row["access_model"]) for row in providers)
    by_source_type = Counter(
        source_type
        for row in providers
        for source_type in row.get("target_source_types", [])
    )
    by_asset_class = Counter(
        asset_class
        for row in providers
        for asset_class in row.get("asset_classes", [])
    )
    return {
        "summary": {
            "provider_count": len(providers),
            "job_count": len(jobs),
            "ready_to_probe": by_status.get("ready_to_probe", 0),
            "planned_adapter": by_status.get("planned_adapter", 0),
            "blocked_by_auth_or_license": by_status.get("blocked_by_auth_or_license", 0),
            "requires_auth_count": sum(1 for row in providers if row["requires_auth"]),
            "requires_license_count": sum(1 for row in providers if row["requires_license"]),
            "by_category": dict(sorted(by_category.items())),
            "by_status": dict(sorted(by_status.items())),
            "by_region": dict(sorted(by_region.items())),
            "by_access_model": dict(sorted(by_access_model.items())),
            "by_source_type": dict(sorted(by_source_type.items())),
            "by_asset_class": dict(sorted(by_asset_class.items())),
        },
        "category_definitions": deepcopy(PROVIDER_CATEGORIES),
        "providers": sorted(providers, key=lambda row: (str(row["priority"]), str(row["category"]), str(row["provider_id"]))),
        "ingestion_jobs": sorted(jobs, key=lambda row: (str(row["priority"]), str(row["status"]), str(row["provider_id"]))),
        "execution_order": [
            "Run ready_to_probe public adapters first and store normalized observations with raw payload hashes.",
            "Open API, exchange, vendor, and issuer access paths for blocked P0 providers.",
            "Build provider-specific catalog adapters before market-data adapters so symbol identity is stable.",
            "Attach provider feed ids, contract addresses, MICs, ISINs, RICs, tickers, and quote conventions to the canonical registry.",
            "Promote only after real-time freshness, depth/spread, benchmark basis, licensing, and replayability checks pass.",
        ],
        "promotion_gates": [
            "canonical symbol and underlying identity mapped",
            "feed, venue, contract, or pool id is stable and replayable",
            "source timestamp passes real-time requirements for the asset type",
            "commercial rights support the intended Blocksize usage and redistribution",
            "observed values align with Blocksize, regulated benchmark, oracle, or futures fair-value checks",
            "source type remains labeled through VWAP, bid/ask, consensus, and downstream API receipts",
        ],
    }


def write_provider_catalog_reports(
    *,
    json_path: str | Path,
    csv_path: str | Path,
) -> dict[str, Any]:
    """Write provider catalog ingestion reports for operations and licensing."""
    catalog = build_provider_catalog()
    json_out = Path(json_path)
    csv_out = Path(csv_path)
    json_out.parent.mkdir(parents=True, exist_ok=True)
    csv_out.parent.mkdir(parents=True, exist_ok=True)
    json_out.write_text(json.dumps(catalog, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    with csv_out.open("w", newline="", encoding="utf-8") as handle:
        fieldnames = [
            "provider_id",
            "name",
            "category",
            "priority",
            "region",
            "ingestion_status",
            "access_model",
            "requires_auth",
            "requires_license",
            "asset_classes",
            "target_source_types",
            "endpoint_families",
            "adapter_lane",
            "promotion_gate",
        ]
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for provider in catalog["providers"]:
            writer.writerow(
                {
                    "provider_id": provider["provider_id"],
                    "name": provider["name"],
                    "category": provider["category"],
                    "priority": provider["priority"],
                    "region": provider["region"],
                    "ingestion_status": provider["ingestion_status"],
                    "access_model": provider["access_model"],
                    "requires_auth": provider["requires_auth"],
                    "requires_license": provider["requires_license"],
                    "asset_classes": json.dumps(provider["asset_classes"]),
                    "target_source_types": json.dumps(provider["target_source_types"]),
                    "endpoint_families": json.dumps(provider["endpoint_families"]),
                    "adapter_lane": provider["adapter_lane"],
                    "promotion_gate": provider["promotion_gate"],
                }
            )
    return catalog
